parts.push('            for (d in pathData) {');
parts.push('                addPath(');
parts.push('                    pathData = PathParser().parsePathString(d).toNodes(),');
parts.push('                    fill = SolidColor(Color.Black),');
parts.push('                )');
parts.push('            }');
parts.push('        }.build()');
parts.push('');

let count = 0;
for (const [prop, file] of Object.entries(ICONS)) {
  const svg = await svgText(file);
  const vb = svg.match(/viewBox="0 0 (\d+(?:\.\d+)?) (\d+(?:\.\d+)?)"/);
  if (!vb) throw new Error(`no viewBox in ${file}.svg`);
  const paths = [...svg.matchAll(/<path\s+d="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length === 0) throw new Error(`no <path d> in ${file}.svg`);
  const quoted = paths.map((p) => JSON.stringify(p));
  parts.push(`    val ${prop} by lazy { vector("${prop}", ${vb[1]}f, ${vb[2]}f, ${quoted.join(', ')}) }`);
  count++;
}
parts.push('}');
parts.push('');

const outDir = join(root, 'app', 'src', 'main', 'java', 'com', 'emberinn', 'app', 'ui', 'icons');
mkdirSync(outDir, { recursive: true });
const outFile = join(outDir, 'FaIcons.kt');
writeFileSync(outFile, parts.join('\n'));
console.log(`wrote ${count} icons -> ${outFile}`);
