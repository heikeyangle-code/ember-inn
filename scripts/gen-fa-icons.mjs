async function svgText(name) {
  const cached = join(cacheDir, `${name}.svg`);
  if (existsSync(cached)) return readFileSync(cached, 'utf8');
  const url = `https://raw.githubusercontent.com/FortAwesome/Font-Awesome/6.x/svgs/solid/${name}.svg`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`fetch ${name}: HTTP ${res.status}`);
  const text = await res.text();
  writeFileSync(cached, text);
  return text;
}

const parts = [];
