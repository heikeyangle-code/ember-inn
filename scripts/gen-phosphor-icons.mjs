#!/usr/bin/env node
/**
 * 从 phosphor-icons/core 官方 SVG 生成 app 内的 PhosphorIcons.kt（Regular 字重）。
 *
 * 用法：
 *   node scripts/gen-phosphor-icons.mjs
 *
 * 环境变量：
 *   PHOSPHOR_ICONS_DIR  官方 core 仓库目录（含 assets/regular/*.svg），
 *                       默认 ~/core-main（GitHub phosphor-icons/core 解压目录）。
 *
 * 为什么不直接用 Maven 上的 Compose Phosphor 库：
 *   com.adamglin:phosphor-icon 与 io.github.dev778g-me:phosphoricon-compose
 *   在 Maven Central 都只发布了 KMP 元数据，Android 目标 jar 缺失（404），
 *   接进 Gradle 必然解析失败。因此把官方 SVG 转成项目内 ImageVector，
 *   零第三方依赖、版本可控、图标可增量补。
 *
 * 生成的 Kotlin 由 androidx PathParser 解析官方 d 路径（256 viewport），
 * 24dp 网格，fill 黑（Icon tint 决定实际颜色）。
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { homedir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = join(
  process.env.PHOSPHOR_ICONS_DIR || join(homedir(), 'core-main'),
  'assets',
  'regular',
);

/** 项目使用名（Kotlin 属性）→ 官方 SVG 文件名（不含 .svg）。 */
const ICONS = {
  ArrowLeft: 'arrow-left',
  Bell: 'bell',
  Book: 'book-open-text',
  BookmarkSimple: 'bookmark-simple',
  CaretDoubleRight: 'caret-double-right',
  CaretLeft: 'caret-left',
  CaretRight: 'caret-right',
  ChartBar: 'chart-bar',
  Close: 'x',
  Continue: 'caret-double-right',
  Copy: 'copy',
  Delete: 'trash-simple',
  DotsThree: 'dots-three',
  DotsThreeVertical: 'dots-three-vertical',
  Edit: 'pencil-simple',
  Eye: 'eye',
  EyeSlash: 'eye-slash',
  FileText: 'file-text',
  Folder: 'folder',
  GitBranch: 'git-branch',
  ImageSquare: 'image-square',
  Lightning: 'lightning',
  Link: 'link',
  List: 'list',
  MaskHappy: 'mask-happy',
  Mic: 'microphone',
  MoreVert: 'dots-three-vertical',
  Person: 'user',
  Plus: 'plus',
  Refresh: 'arrows-clockwise',
  Search: 'magnifying-glass',
  Send: 'paper-plane-right',
  Sparkle: 'sparkle',
  Settings: 'gear-six',
  Share: 'share-network',
  SpeakerHigh: 'speaker-high',
  Star: 'star',
  Stop: 'square',
  User: 'user',
};

function svgPathData(name) {
  const file = join(sourceDir, `${name}.svg`);
  const svg = readFileSync(file, 'utf8');
  const paths = [...svg.matchAll(/<path\s+d="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length === 0) {
    throw new Error(`no <path d> found in ${file}`);
  }
  return paths;
}

const entries = Object.entries(ICONS);
const parts = [];
parts.push(`// GENERATED by scripts/gen-phosphor-icons.mjs — DO NOT EDIT BY HAND.`);
parts.push(`// 官方 Phosphor Icons（Regular 字重）v2.x，源自 phosphor-icons/core 的 assets/regular/*.svg。`);
parts.push(`package com.emberinn.app.ui.icons`);
parts.push(``);
parts.push(`import androidx.compose.ui.graphics.Color`);
parts.push(`import androidx.compose.ui.graphics.SolidColor`);
parts.push(`import androidx.compose.ui.graphics.vector.ImageVector`);
parts.push(`import androidx.compose.ui.graphics.vector.PathParser`);
parts.push(`import androidx.compose.ui.unit.dp`);
parts.push(``);
parts.push(`/**`);
parts.push(` * Phosphor Regular 图标集（24dp 网格 / 256 viewport / 圆头圆角）。`);
parts.push(` * 用法：Icon(imageVector = PhosphorIcons.Search, tint = MaterialTheme.colorScheme.onSurfaceVariant)`);
parts.push(` * 默认 tint 由调用处决定：常规 onSurfaceVariant，激活 primary，警示 error。`);
parts.push(` */`);
parts.push(`object PhosphorIcons {`);
parts.push(``);
parts.push(`    private fun vector(name: String, vararg pathData: String): ImageVector =`);
parts.push(`        ImageVector.Builder(`);
parts.push(`            name = name,`);
parts.push(`            defaultWidth = 24.dp,`);
parts.push(`            defaultHeight = 24.dp,`);
parts.push(`            viewportWidth = 256f,`);
parts.push(`            viewportHeight = 256f,`);
parts.push(`        ).apply {`);
parts.push(`            for (d in pathData) {`);
parts.push(`                addPath(`);
parts.push(`                    pathData = PathParser().parsePathString(d).toNodes(),`);
parts.push(`                    fill = SolidColor(Color.Black),`);
parts.push(`                )`);
parts.push(`            }`);
parts.push(`        }.build()`);
parts.push(``);
for (const [prop, file] of entries) {
  const paths = svgPathData(file);
  const quoted = paths.map((p) => JSON.stringify(p));
  parts.push(`    val ${prop} by lazy { vector("${prop}", ${quoted.join(', ')}) }`);
}
parts.push(`}`);
parts.push(``);

const outDir = join(root, 'app', 'src', 'main', 'java', 'com', 'emberinn', 'app', 'ui', 'icons');
mkdirSync(outDir, { recursive: true });
const outFile = join(outDir, 'PhosphorIcons.kt');
writeFileSync(outFile, parts.join('\n'));
console.log(`wrote ${entries.length} icons -> ${outFile}`);
