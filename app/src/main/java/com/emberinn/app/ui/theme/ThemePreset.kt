    val shape: String = "default",
    /** 间距节奏倍数（>1 更松散，<1 更紧凑）；默认 1.0。 */
    val spacing: Float = 1f,
    /** 动效速度倍数（>1 更快，<1 更慢）；默认 1.0。 */
    val motionScale: Float = 1f,
    // ---- 官方 SillyTavern 字段默认值（null=跟随 M3 自动生成；酒馆官方主题填官方真值） ----
    val stBody: Color? = null,
    val stEm: Color? = null,
    val stUnderline: Color? = null,
    val stQuote: Color? = null,
    val stUserBubble: Color? = null,
    val stBotBubble: Color? = null,
    val stBorder: Color? = null,
    val stShadow: Color? = null,
    val stBlurTint: Color? = null,
    // ---- M3 角色覆盖（酒馆官方主题填官方 SmartTheme 真值；null=由 seed 生成） ----
    val schemePrimary: Color? = null,
    val schemeSecondary: Color? = null,
    val schemeTertiary: Color? = null,
    val schemeBackground: Color? = null,
    val schemeOnBackground: Color? = null,
    val schemeSurface: Color? = null,
    val schemeOnSurface: Color? = null,
    // ---- 艺术向扩展（古典油画/黑暗奇幻主题语言；默认值 = 不启用，兼容官方与角色卡动态主题） ----
    /** 明暗对照（chiaroscuro）：>1 容器色阶梯拉开、光影更戏剧化；默认 1 = M3 原节奏。 */
    val contrast: Float = 1f,
    /** 宝石点缀色：红宝石/蓝宝石/星尘——氛围光晕与预览宝石位（null=不启用）。 */
    val gem: Color? = null,
    /** 金属工艺色：古金/旧银/青铜——主题卡描边与装饰细节（null=不启用）。 */
    val metal: Color? = null,
    /** 底材纹理配方：六图元（织纹/布点/排线/交叉排线/纤维/颗粒）任意组合，各主题自由定制。 */
