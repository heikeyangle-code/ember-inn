    /** 天空氛围色：深色模式页面顶部极淡渐变天色——红月、烟雾战场（null=不启用）。 */
    val auraTop: Color? = null,
    /** 浅色模式天空氛围：象牙晨光、绯色薄暮等（null=浅色不画天空）。 */
    val auraTopLight: Color? = null,
)

